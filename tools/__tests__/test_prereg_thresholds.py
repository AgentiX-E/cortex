"""Numeric thresholds written in prose, and the rows that are supposed to be the only copy.

## The defect this file exists for

`docs/PREREG-READER-AXIS.md` section 2 registers `M1`'s success condition as "**>= 5 points**".
`packages/cortex-eval/src/acceptance.ts` registers the same criterion as `threshold: 0.03`. Two copies
of one threshold, five sections apart, written months apart, and **nothing compared them** -- so the
row that a build fails on and the paragraph a reader is persuaded by could disagree indefinitely.

This is the direction the acceptance matrix cannot see. The matrix is generated from the code, and
`tools/docs-crosscheck.mjs` re-derives every number it prints, so a *row* cannot drift from its
producer. A `PREREG-*.md` is not generated by anything: it is a promise written before the code, which
is the whole point of a pre-registration, and a promise that is never read is the one class of number
this project has never checked.

## What is checked

`docs/PREREG-READER-AXIS.md` section 7.1 states, in the same sentence, which row wins and what number it
carries ("row `M1` reads `>= 3.0pp`"). That sentence is parsed and compared against the row. A change to
either side fails -- which is the intended cost: amending a pre-registered threshold should require
amending the paragraph that says so, and that is the last time it can be done by hand.

## Why the scan and not only the one pair

A registry that lists only `READER-AXIS` would pass forever while the next pre-registration writes a
`>= N points` bar nobody reads. So every `docs/PREREG-*.md` is scanned for a points-threshold claim and
must either be in the registry or be listed as exempt with a reason. The exemption list is short on
purpose, and an unregistered claim fails as an unknown rather than passing as harmless.
"""

from __future__ import annotations

import pathlib
import re

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / 'docs'
ACCEPTANCE = ROOT / 'packages' / 'cortex-eval' / 'src' / 'acceptance.ts'

#: `[(document, criterion id, the number the document states)]`.
#:
#: The number is what the *document* says, so the pair fails if the document is reworded and passes only
#: while the two agree. A registry of the code's value would be a third copy and would check nothing.
REGISTERED: list[tuple[str, str, float]] = [
    ('PREREG-READER-AXIS.md', 'M1', 3.0),
]

#: Documents that state points bars deliberately outside the matrix, with the reason they have no row.
#:
#: An entry here is a claim that the bars are measured by something other than `acceptance.ts`, and the
#: reason has to name that something. It is not a suppression: `test_an_exemption_is_scoped_to_per_dispatch_bars`
#: checks that every bar in an exempt document sits beside a run id, so a *standing* bar added to an exempt
#: file fails here rather than passing as one of the crowd.
EXEMPT: dict[str, str] = {
    'PREREGISTRATION-CORTEX-MEMORY-ARM.md': (
        'every bar in it is a per-dispatch prediction for one numbered run, read by '
        '`tools/readout-arm-run.py --registration` against that run own artifact; a standing bar is a row '
        'in `acceptance.ts` and none of these is one'
    ),
}

_RUN_ID = re.compile(r'\b\d{8,11}\b')

#: A bar quoted while *reporting a result* is a record and not a threshold. `R1 (|delta| >= 5 points) met at
#: 7.20` states what a past check asked and what it returned; reading it as a standing bar would demand a
#: matrix row for every number any section ever quoted back.
_REPORTED = re.compile(r'\b(?:met|missed|returned|against)\b')

_ROW_THRESHOLD = re.compile(
    r"id:\s*'(?P<id>[A-Z]\d+)'(?P<body>.*?)\n  \},", re.DOTALL
)
_THRESHOLD_FIELD = re.compile(r'threshold:\s*(?P<value>[0-9.]+)')
_UNIT_FIELD = re.compile(r"unit:\s*'(?P<unit>points|ratio|count)'")
_POINTS_CLAIM = re.compile(r'`?\u2265\s*(?P<value>[0-9]+(?:\.[0-9]+)?)\s*(?:points|pp)`?')


def acceptance_rows() -> dict[str, tuple[float, str]]:
    """Every criterion in the matrix, as `{id: (threshold, unit)}`."""
    source = ACCEPTANCE.read_text()
    rows: dict[str, tuple[float, str]] = {}
    for match in _ROW_THRESHOLD.finditer(source):
        body = match.group('body')
        threshold = _THRESHOLD_FIELD.search(body)
        unit = _UNIT_FIELD.search(body)
        if threshold is None or unit is None:
            continue
        rows[match.group('id')] = (float(threshold.group('value')), unit.group('unit'))
    return rows


def prereg_documents() -> list[pathlib.Path]:
    return sorted(DOCS.glob('PREREG*.md'))


def documentary_claim(path: pathlib.Path, criterion: str) -> float | None:
    """The points bar `path` states for `criterion`, or `None` when it states none.

    Scoped to a window around the criterion's own identifier rather than to the whole document: a
    pre-registration is long and its sections discuss other systems' numbers, so a document-wide search
    would compare our threshold against a competitor's and report a disagreement that is not one.
    """
    text = path.read_text()
    position = text.find(f'`{criterion}`')
    if position < 0:
        return None
    window = text[position : position + 400]
    match = _POINTS_CLAIM.search(window)
    return None if match is None else float(match.group('value'))


@pytest.mark.parametrize('document, criterion, stated', REGISTERED)
def test_the_preregistration_and_the_row_carry_the_same_bar(
    document: str, criterion: str, stated: float
) -> None:
    rows = acceptance_rows()
    assert criterion in rows, f'{criterion} is not a row in acceptance.ts'
    threshold, unit = rows[criterion]
    assert unit == 'points', f'{criterion} is measured in {unit}, so a points bar cannot match it'

    claim = documentary_claim(DOCS / document, criterion)
    assert claim is not None, f'{document} states no points bar for {criterion}'
    assert claim == pytest.approx(stated), (
        f'{document} no longer states {stated} for {criterion}; the registry is stale'
    )
    assert threshold == pytest.approx(claim / 100), (
        f'{document} states {claim} points for {criterion} and acceptance.ts registers '
        f'{threshold}; one of them is a second copy that nothing read'
    )


def test_every_document_that_states_a_points_bar_is_registered() -> None:
    registered = {document for document, _, _ in REGISTERED}
    unregistered: list[str] = []
    for path in prereg_documents():
        if path.name in registered or path.name in EXEMPT:
            continue
        for match in _POINTS_CLAIM.finditer(path.read_text()):
            # A bar is a bar whether or not it is written next to a row id; the claim regex requires the
            # `points` unit, which is what keeps this from firing on ">= 5 occurrences".
            unregistered.append(f'{path.name}: {match.group(0).strip()}')
    assert not unregistered, (
        'these documents state a points threshold that no row checks, so nothing can notice when the '
        'code disagrees: ' + '; '.join(unregistered)
    )


def test_an_exemption_is_scoped_to_per_dispatch_bars() -> None:
    # The whole value of the exemption is that it is narrow. A standing bar -- one that is supposed to hold
    # for every future run rather than for a named past one -- has no run id anywhere near it, so it fails
    # here instead of sheltering inside a document whose other bars are all predictions.
    for document in EXEMPT:
        text = (DOCS / document).read_text()
        orphaned = [
            match.group(0).strip()
            for match in _POINTS_CLAIM.finditer(text)
            if not _REPORTED.search(text[max(0, match.start() - 40) : match.end() + 140])
            and not _RUN_ID.search(text[max(0, match.start() - 2000) : match.end() + 2000])
        ]
        assert not orphaned, (
            f'{document} is exempt because its bars are per-dispatch, and these have no run id within '
            f'two thousand characters: {orphaned}'
        )


def test_the_exemption_list_names_a_measurement() -> None:
    # An exemption with an empty reason is a suppression. The reason has to name what measures the bar
    # instead, so that a reader can go and check that thing.
    for document, reason in EXEMPT.items():
        assert (DOCS / document).exists(), f'{document} is exempted and does not exist'
        assert len(reason.strip()) >= 40, f'{document} is exempted without saying what measures it'
