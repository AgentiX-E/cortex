"""Cortex as a provider inside Maximem's LongMemEval harness.

Their harness is the only other published pipeline that runs this dataset, and `MEASURE-COMPETITOR-PAIRING.md`
§5 licenses exactly one run against it: **same 500 questions, same answer prompt, same judge**, our retrieval in
place of theirs. That is the only way to separate "the 4.40-point gap is harness" from "the gap is system", and
neither this repository's artifacts nor their published number can answer it alone.

## Where this file has to live

Inside their tree, at `adapters/cortex_adapter.py`, next to `synap_adapter.py`. Their runner imports adapters by
module name (`runner/registry.py`), so a file outside `adapters/` is a provider their harness cannot name. The
copy in this repository is the source of truth; `tools/competitor-adapter/README.md` has the two commands that
put it there and the reason it is a copy rather than a dependency.

## What is measured, and what is held fixed

| held by them | held by us |
| --- | --- |
| the answer prompt (21,366 characters, `LME_answering_prompt.md`) | the retrieval: admission, relevance signal, session budget |
| the answer model and the judge | the rendering of the turns it hands back |
| the 500 questions, the haystack | nothing else |

The answer is generated by their prompt, so this run **cannot** see our contracts, our evidence rendering or our
reply repairs. That is the point: a comparison in which both sides brought their own reader would be two
systems plus one judge, and the number would belong to neither.

## Why the store is a subprocess

`tools/competitor-sut/PROTOCOL.md` already defines the three operations and their failure semantics, and this
repository's store is a Node package with a build step. Reusing that protocol in the other direction is what
keeps one document describing both directions. `bridge.mjs` is the child.

## The one formatting decision

Each turn is sent as `[<timestamp>] <role>: <text>`, which is this product's shipped corpus rendering
(`[2023/05/20 (Sat) 03:51] user: ...`). The prefix is not decoration: every temporal question in the dataset
resolves relative expressions against that date, and a store handed bare text would be measured on a corpus
this product never sees. Their other adapters make the same choice for their own renderings.
"""

from __future__ import annotations

import asyncio
import json
import os
import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional

from adapters.base_adapter import (
    IndexingProgressCallback,
    IngestOptions,
    IngestResult,
    Provider,
    ProviderConfig,
    SearchOptions,
    UnifiedSession,
)

# `tools/competitor-adapter/bridge.mjs`, found relative to this file's own location in their tree: the adapter
# is copied into `adapters/`, and the bridge is copied beside it. An absolute path from an environment variable
# would be a second way to configure a run and a second way to get it wrong.
BRIDGE = Path(__file__).with_name("cortex_bridge.mjs")

DEFAULT_TIMEOUT_SECONDS = 900.0


class CortexProvider(Provider):
    """Retrieval only: `search` never generates, so the answer is their prompt's."""

    name = "cortex"

    def __init__(self) -> None:
        self._process: Optional[asyncio.subprocess.Process] = None
        self._lock = asyncio.Lock()
        self._manifest: Dict[str, Any] = {}
        self._timeout = float(os.environ.get("CORTEX_ADAPTER_TIMEOUT", DEFAULT_TIMEOUT_SECONDS))
        self.last_ingest: Dict[str, Any] = {}

    # ── lifecycle ──────────────────────────────────────────────────────

    async def initialize(self, config: ProviderConfig) -> None:
        node = os.environ.get("CORTEX_ADAPTER_NODE") or shutil.which("node")
        if node is None:
            raise RuntimeError(
                "node is not on PATH; the bridge is a Node program and the store it drives is a Node package"
            )
        if not BRIDGE.is_file():
            raise RuntimeError(
                f"bridge not found at {BRIDGE}; copy tools/competitor-adapter/bridge.mjs beside this adapter"
            )
        self._process = await asyncio.create_subprocess_exec(
            node,
            str(BRIDGE),
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=None,  # inherited: a bridge that logs keeps its log without corrupting the channel
        )
        manifest = await self._call({"op": "manifest"})
        for field in ("name", "build", "version"):
            if not isinstance(manifest.get(field), str):
                raise RuntimeError(f"bridge manifest has no string `{field}`: {manifest!r}")
        self._manifest = manifest
        # `container_tag` is their user scope. This store has one container per process, which is what
        # `clear()` resets, so the tag needs no handling here -- recorded rather than silently dropped.
        self._manifest["container_tag"] = config.get("container_tag", "")

    async def close(self) -> None:
        if self._process is None or self._process.returncode is not None:
            return
        try:
            await self._call({"op": "shutdown"})
        except Exception:  # noqa: BLE001 - a store that will not shut down politely gets killed below
            pass
        finally:
            try:
                await asyncio.wait_for(self._process.wait(), timeout=10)
            except asyncio.TimeoutError:
                self._process.kill()
            self._process = None

    # ── the protocol ───────────────────────────────────────────────────

    async def _call(self, request: Dict[str, Any]) -> Dict[str, Any]:
        if self._process is None or self._process.stdin is None or self._process.stdout is None:
            raise RuntimeError("the bridge is not running; initialize() was not awaited")
        line = json.dumps(request, separators=(",", ":"))
        async with self._lock:
            self._process.stdin.write((line + "\n").encode())
            await self._process.stdin.drain()
            try:
                raw = await asyncio.wait_for(self._process.stdout.readline(), timeout=self._timeout)
            except asyncio.TimeoutError as error:
                raise TimeoutError(
                    f"cortex bridge did not answer {request.get('op')!r} within {self._timeout}s"
                ) from error
        if not raw:
            raise RuntimeError(
                f"cortex bridge closed the channel while answering {request.get('op')!r} "
                f"(exit code {self._process.returncode})"
            )
        try:
            response = json.loads(raw.decode())
        except json.JSONDecodeError as error:
            raise RuntimeError(
                f"cortex bridge wrote a line that is not JSON: {raw[:200]!r}"
            ) from error
        if response.get("ok") is not True:
            # A refusal, not a crash: their runner records it per question, which is how a system that
            # declines a corpus is distinguished from one that returned nothing.
            raise RuntimeRefusal(str(response.get("error", "no error given")))
        return response

    # ── the five methods their ABC requires ────────────────────────────

    async def ingest(
        self, sessions: List[UnifiedSession], options: IngestOptions
    ) -> IngestResult:
        payload = [self._payload(session) for session in sessions]
        response = await self._call({"op": "ingest", "sessions": payload})
        # What the store took, kept because an ingest that silently dropped part of the corpus produces a score
        # that reads as a retrieval failure. `PROTOCOL.md` makes this a required field for that reason.
        self.last_ingest = {
            "offered": len(sessions),
            "sessions": response.get("sessions"),
            "turns": response.get("turns"),
            "skipped": response.get("skipped", []),
        }
        return IngestResult(document_ids=[session.session_id for session in sessions])

    async def await_indexing(
        self,
        result: Any,
        container_tag: str,
        on_progress: Optional[IndexingProgressCallback] = None,
    ) -> None:
        """Nothing to wait for: the index is the array the ingest appended to."""
        if on_progress is not None:
            on_progress(type("Progress", (), {"completed_ids": [], "failed_ids": [], "total": 0})())

    async def search(self, query: str, options: SearchOptions) -> List[Any]:
        limit = options.limit or 20
        response = await self._call({"op": "search", "query": query, "limit": limit})
        hits = response.get("hits", [])
        if len(hits) > limit:
            raise RuntimeError(
                f"cortex bridge returned {len(hits)} hits for a limit of {limit}; the protocol makes the "
                "ceiling the caller's contract"
            )
        return [
            {
                "memory": hit.get("text", ""),
                "score": hit.get("score"),
                "said_at": _iso(hit.get("at")),
            }
            for hit in hits
        ]

    async def clear(self, container_tag: str) -> None:
        # One store per process: resetting it is what stops the next container answering from the last one's
        # sessions, which would score well and measure nothing.
        await self._call({"op": "reset"})

    # ── formatting ─────────────────────────────────────────────────────

    def _payload(self, session: UnifiedSession) -> Dict[str, Any]:
        at = _epoch_ms(_session_timestamp(session))
        return {
            "id": session.session_id,
            "at": at,
            "turns": [
                {
                    "role": message.role,
                    "content": _rendered(message),
                }
                for message in session.messages
            ],
        }


class RuntimeRefusal(RuntimeError):
    """The store answered `{"ok": false}`: a per-question refusal, not a run failure."""


def _rendered(message: Any) -> str:
    stamp = (message.timestamp or "").strip()
    speaker = message.role
    text = (message.content or "").strip()
    if not stamp:
        return f"{speaker}: {text}"
    return f"[{stamp}] {speaker}: {text}"


def _session_timestamp(session: UnifiedSession) -> Optional[str]:
    metadata = session.metadata or {}
    if metadata.get("timestamp"):
        return str(metadata["timestamp"])
    for message in session.messages:
        if message.timestamp:
            return str(message.timestamp)
    return None


def _epoch_ms(stamp: Optional[str]) -> int:
    if not stamp:
        return 0
    from dateutil import parser as date_parser

    try:
        return int(date_parser.parse(stamp).timestamp() * 1000)
    except (ValueError, OverflowError):
        return 0


def _iso(epoch_ms: Optional[int]) -> Optional[str]:
    if not epoch_ms:
        return None
    from datetime import datetime, timezone

    return datetime.fromtimestamp(epoch_ms / 1000, tz=timezone.utc).isoformat()
