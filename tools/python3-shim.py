"""Install, inspect and uninstall the `python3` shim described in `docs/OPS-SHELL-INTERPOLATION.md` 4g.

## Why this file exists, and the defect it closes

The shim is the only mechanism in this repository that sits in the path of a **typed**
command, and it was the one thing with no committed source. It lived at
`/root/.pyenv/shims/python3` as a 2,680-byte file produced by hand, documented in prose,
and therefore **removed by whatever replaced the image** -- silently, because nothing in
the repository could tell that it had been the guard shim rather than pyenv's own
dispatcher.

The observable consequence was measured on a fresh image: `python3 -m pytest
tools/__tests__` reported **3 failed** in `test_shim_guard.py`, and `pnpm check` was red
for a reason that named the wrong problem. The suite's own `skipif` could not help,
because it asked "is there an executable file at the shim's home" and pyenv's dispatcher
answers yes. A gate that cannot tell its own instrument from a stranger's is the failure
mode this repository keeps writing about; here it was in the gate itself.

So the source moves into the repository, and the environment change becomes a command:

    python3 tools/python3-shim.py --install     # idempotent; backs up what it replaces
    python3 tools/python3-shim.py --check       # identity of what is at the home now
    python3 tools/python3-shim.py --uninstall   # restores the backup

## What the shim does

If the first argument is `-c` and the payload contains an interpolation opener, it asks
`tools/check-shell-interpolation.py --c-payload` about the payload **before** the real
interpreter runs, and refuses on a non-zero answer with the guard's own message plus one
line naming the way out. Everything else is `exec`ed straight through.

## Failure is OPEN, deliberately

A guard that blocks work when its own file is missing is a guard people route around,
and the cost of that exceeds the hazard it prevents. So: unreadable marker, missing
guard, unresolvable interpreter -- each falls through to the interpreter, and the shim
prints nothing. The **identity** question is answered separately by `--check`, which is
what a test can assert without making a missing file break every `python3` invocation.

## Where the guard is looked up, and why not only at install time

A shim that bakes one checkout's absolute path guards exactly that checkout, and the
repository is routinely cloned twice. The shim therefore walks **up from `$PWD`** looking
for `tools/check-shell-interpolation.py`, bounded at eight levels, and falls back to the
path recorded at install time. Both are tried; either one is enough.
"""

from __future__ import annotations

import argparse
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

# Identifies the file as OURS. Read back by `identity()` and by
# `tools/__tests__/test_shim_guard.py`, which imports this module rather than restating
# the string -- a second copy is the drift that makes a gate believe a stranger is its
# own instrument.
MARKER = 'cortex-python3-shim v1'

# The shim's documented home. `--home` overrides it, and the tests take the same default
# from `default_home()`, so a host that installs elsewhere is a one-line change rather
# than a second hardcoded path.
DEFAULT_HOME = Path('/root/.pyenv/shims/python3')

# Where the displaced file is kept. Named rather than dated: one backup is enough to
# restore, and a timestamped family would make `--uninstall` guess.
BACKUP_SUFFIX = '.cortex-displaced'

# Interpolation opener, assembled rather than written. A literal two-character opener in
# this file would be exactly the hazard the guard scans for -- and the guard scans
# `tools/` sources, so writing it here would have to be suppressed rather than avoided.
DOLLAR = chr(36)
BRACE = chr(123)


def default_home() -> Path:
    """The shim's home, overridable so that a second install target is not a second copy."""
    override = os.environ.get('CORTEX_SHIM_HOME')
    return Path(override) if override else DEFAULT_HOME


def _bash_source(real_python: str, guard: str) -> str:
    """The shim, with the two absolute paths substituted.

    Written as one f-string with `{...}` placeholders for the two paths and **no** other
    braces, so `str.format` cannot be reached by accident and the only substitutions are
    the two named ones. The interpolation opener is built from the two constants above
    and interpolated as `opener`, which is why no bare opener appears in this source.
    """
    opener = DOLLAR + BRACE
    return f'''#!/usr/bin/env bash
# {MARKER} -- generated by tools/python3-shim.py. Do not edit; edit the generator.
#
# The `python3` that runs a typed command, with the payload rule in the path of it.
# See docs/OPS-SHELL-INTERPOLATION.md 4g.
#
# Failure is OPEN: if this file cannot locate the guard or the interpreter, the
# interpreter runs and nothing is printed. A net that blocks work when its own file is
# missing is a net people route around.
set -u

REAL_PYTHON={real_python!r}
FALLBACK_GUARD={guard!r}
OPENER={opener!r}

locate_guard() {{
  local dir i parent
  dir=$PWD
  i=0
  while [ "$i" -lt 8 ]; do
    if [ -f "$dir/tools/check-shell-interpolation.py" ]; then
      printf '%s\\n' "$dir/tools/check-shell-interpolation.py"
      return 0
    fi
    parent=$(dirname "$dir")
    [ "$parent" = "$dir" ] && break
    dir=$parent
    i=$((i + 1))
  done
  if [ -f "$FALLBACK_GUARD" ]; then
    printf '%s\\n' "$FALLBACK_GUARD"
    return 0
  fi
  return 1
}}

refuse() {{
  local payload guard report
  payload=$1
  guard=$(locate_guard) || return 0
  if report=$("$REAL_PYTHON" "$guard" --c-payload "$payload" python 2>&1 1>/dev/null); then
    return 0
  fi
  printf '%s\\n' "$report" >&2
  printf '\\nThe way out: write the program to a file and run the file, or pipe it on stdin:\\n' >&2
  printf '  %s tools/exec-python.py - <<'"'"'PROBE'"'"'\\n' "$REAL_PYTHON" >&2
  return 1
}}

if [ "$#" -ge 2 ] && [ "$1" = "-c" ]; then
  case "$2" in
    *"$OPENER"*)
      # Only payloads that carry an opener are worth a subprocess. This is the hot path
      # of every python3 invocation in the image, and a guard that costs 30 ms on
      # `print(1)` would be turned off rather than fixed.
      refuse "$2" || exit 1
      ;;
  esac
fi

exec "$REAL_PYTHON" "$@"
'''


def identity(path: Path | None = None) -> str:
    """What is at `path` right now: `absent`, `inert`, `guard`, or `foreign`.

    ## Why four answers and not a boolean

    The old predicate answered "is there an executable file here", and pyenv's own
    dispatcher -- which is what a stock pyenv image puts at this exact path -- answers
    yes. The suite then ran the intercept tests against a shim that does not intercept,
    and failed for a reason that read like a code defect.

    `inert` is the fourth, and it is not a decoration: the marker is read **before** the
    executable bit is consulted, so a copy that lost its mode (`chmod` is not preserved by
    every archive and image layer) is distinguishable from a file that is not ours. Both
    stop the net from working; only one of them means "reinstall", and a diagnosis that
    cannot tell them apart sends the operator to the wrong command.
    """
    target = path if path is not None else default_home()
    try:
        if not target.exists():
            return 'absent'
        head = target.read_text(encoding='utf-8', errors='replace')[:4096]
        executable = bool(target.stat().st_mode & stat.S_IXUSR)
    except OSError:
        return 'absent'
    if MARKER not in head:
        return 'foreign' if executable else 'absent'
    return 'guard' if executable else 'inert'


def resolve_real_python(home: Path) -> str | None:
    """The interpreter the shim will `exec`, found by walking `PATH` past `home`.

    Excluded by absolute path rather than by name: on a pyenv image `python3` on `PATH`
    **is** the file being replaced, so a name-based lookup would make the shim exec
    itself and recurse until the kernel refuses. Measured on the re-imaged host: the
    first `python3` on `PATH` is the shim home, the second is
    `/usr/bin/python3`, and the interpreter in use is neither.
    """
    home_resolved = home.resolve()
    candidates: list[str] = []
    for entry in os.environ.get('PATH', '').split(os.pathsep):
        if not entry:
            continue
        candidate = Path(entry) / 'python3'
        if not candidate.is_file():
            continue
        if candidate.resolve() == home_resolved:
            continue
        candidates.append(str(candidate))
    return candidates[0] if candidates else None


def install(home: Path, real_python: str, guard: Path) -> int:
    """Write the shim, displacing -- not deleting -- whatever is there.

    Idempotent: a second run over our own shim rewrites it and leaves the backup alone,
    because the displaced file is pyenv's dispatcher and a second `--install` must not
    overwrite the only copy of it with a copy of ourselves.
    """
    current = identity(home)
    if current == 'foreign':
        backup = home.with_suffix(home.suffix + BACKUP_SUFFIX)
        if not backup.exists():
            shutil.copy2(home, backup)
            print(f'displaced {home} -> {backup}')
        else:
            print(f'kept existing backup {backup}')
    elif current == 'absent' and home.exists():
        print(f'{home} exists but is not executable; leaving it in place')

    home.parent.mkdir(parents=True, exist_ok=True)
    home.write_text(_bash_source(real_python, str(guard)), encoding='utf-8')
    home.chmod(0o755)
    print(f'installed {MARKER} at {home} (interpreter {real_python})')
    return 0


def uninstall(home: Path) -> int:
    """Remove our shim and restore the displaced file, if there is one.

    Refuses to touch a `foreign` file: `--uninstall` on a host that never installed this
    must not delete the pyenv dispatcher, which is the same class of mistake as
    `--install` overwriting it without a backup.
    """
    current = identity(home)
    if current != 'guard':
        print(f'nothing to uninstall: {home} is `{current}`, not `{MARKER}`')
        return 1
    backup = home.with_suffix(home.suffix + BACKUP_SUFFIX)
    home.unlink()
    if backup.exists():
        shutil.move(str(backup), str(home))
        print(f'restored {backup} -> {home}')
    else:
        print(f'removed {home}; no displaced file to restore')
    return 0


def check(home: Path) -> int:
    """Print the identity and exit 0 only when it is ours.

    Non-zero on `foreign` is deliberate: that state means a file is occupying the guard's
    address and the guard is **not** in the path of a typed command, which is the
    condition that produced the seventh recurrence. `absent` is non-zero too, because
    `--check` is what a human or a CI step runs to ask "is the net up", and "the net is
    not here" is the answer that must not be read as success.
    """
    current = identity(home)
    print(f'{home}: {current}')
    if current == 'guard':
        return 0
    if current == 'foreign':
        print(
            'A file is at the shim home that this repository did not write. The payload\n'
            'guard is therefore NOT in the path of a typed command. Reinstall with:\n'
            f'  python3 tools/python3-shim.py --install --home {home}',
            file=sys.stderr,
        )
    elif current == 'inert':
        print(
            'This repository\'s shim is at the home but is not executable, so it cannot\n'
            'run and the payload guard is NOT in the path of a typed command. Restore the\n'
            'mode, or reinstall:\n'
            f'  python3 tools/python3-shim.py --install --home {home}',
            file=sys.stderr,
        )
    else:
        print(
            'The shim is not installed. It is an environment change and not a committed\n'
            'file, so a re-image removes it. Install it with:\n'
            f'  python3 tools/python3-shim.py --install --home {home}',
            file=sys.stderr,
        )
    return 1


def self_test(home: Path) -> int:
    """Prove the shim source refuses the hazard and passes an ordinary payload.

    Written as a subprocess round-trip rather than as a string assertion: the property
    that matters is what the shell does with the file, and a test that greps the source
    for the guard call passes on a shim whose `case` pattern is wrong.
    """
    interpreter = resolve_real_python(home)
    if interpreter is None:
        print('cannot self-test: no interpreter on PATH outside the shim home', file=sys.stderr)
        return 1
    guard = Path(__file__).resolve().parent / 'check-shell-interpolation.py'
    scratch = home.with_suffix('.selftest')
    scratch.write_text(_bash_source(interpreter, str(guard)), encoding='utf-8')
    scratch.chmod(0o755)
    ok = True
    try:
        clean = subprocess.run([str(scratch), '-c', 'print(1 + 1)'], capture_output=True, text=True)
        if clean.returncode != 0 or '2' not in clean.stdout:
            print(f'self-test: an ordinary payload did not run: {clean.stderr}', file=sys.stderr)
            ok = False
        hazard = 'print(' + DOLLAR + BRACE + 'x:.3f' + chr(125) + ')'
        refused = subprocess.run([str(scratch), '-c', hazard], capture_output=True, text=True)
        if refused.returncode == 0:
            print('self-test: the hazard was allowed through', file=sys.stderr)
            ok = False
        elif 'sits inside a `python` payload' not in refused.stderr:
            print(
                'self-test: the payload was refused by the interpreter rather than by the '
                f'guard: {refused.stderr}',
                file=sys.stderr,
            )
            ok = False
        elif 'exec-python.py' not in refused.stderr:
            print('self-test: the refusal does not name the way out', file=sys.stderr)
            ok = False
    finally:
        scratch.unlink(missing_ok=True)
    print('self-test: ' + ('ok' if ok else 'failed'))
    return 0 if ok else 1


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--home', type=Path, default=None, help='shim path (default: 4g home)')
    parser.add_argument('--real', dest='real', default=None, help='interpreter the shim execs')
    parser.add_argument('--guard', type=Path, default=None, help='guard script to call')
    parser.add_argument('--print', dest='emit', action='store_true', help='print the shim source')
    parser.add_argument('--install', action='store_true')
    parser.add_argument('--uninstall', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args(argv[1:])

    home = args.home or default_home()
    guard = args.guard or (Path(__file__).resolve().parent / 'check-shell-interpolation.py')

    if args.emit:
        interpreter = args.real or resolve_real_python(home) or '/usr/bin/python3'
        sys.stdout.write(_bash_source(interpreter, str(guard)))
        return 0
    if args.check:
        return check(home)
    if args.uninstall:
        return uninstall(home)
    if args.self_test:
        return self_test(home)
    if args.install:
        interpreter = args.real or resolve_real_python(home)
        if interpreter is None:
            print(
                'refusing to install: no python3 on PATH outside the shim home would be '
                'left to exec, so the shim would exec itself',
                file=sys.stderr,
            )
            return 1
        return install(home, interpreter, guard)

    parser.print_help()
    return 2


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
